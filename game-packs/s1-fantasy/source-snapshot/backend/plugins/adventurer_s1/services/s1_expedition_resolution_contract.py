"""S1 高危探险因果底稿的结构基数合同。"""


S1_EXPEDITION_RESOLUTION_MAX_EVENT_FACTS = 64
S1_EXPEDITION_RESOLUTION_MAX_ESTABLISHED_SOURCES = 32
S1_EXPEDITION_RESOLUTION_MAX_MEMBERS = 16
S1_EXPEDITION_RESOLUTION_MAX_CHANGES_PER_MEMBER = 32
S1_EXPEDITION_RESOLUTION_MAX_ALLOCATIONS_PER_CHANGE = 16

# 64 是模型应遵守的正常体积目标，不是会丢弃独立防护记录的业务边界。
S1_EXPEDITION_RESOLUTION_LEDGER_NORMAL_LIMIT = 64

# 每个通过消费合同的账本项都必须至少被一次 mitigation allocation 引用；
# 因此全部成员、全部变化和每次变化的分配槽位乘积，才是可消费账本的
# 机械硬上限。超过此值必然包含无法被消费的账本项，仍应 fail-closed。
S1_EXPEDITION_RESOLUTION_LEDGER_HARD_LIMIT = (
    S1_EXPEDITION_RESOLUTION_MAX_MEMBERS
    * S1_EXPEDITION_RESOLUTION_MAX_CHANGES_PER_MEMBER
    * S1_EXPEDITION_RESOLUTION_MAX_ALLOCATIONS_PER_CHANGE
)
